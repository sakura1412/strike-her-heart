"""Render a private, self-contained workflow snapshot from an already checked summary."""

from datetime import datetime, timezone
import json
import os
from pathlib import Path
import tempfile

PLACEHOLDER = "/*__SHH_WORKFLOW_DATA__*/null"
MARKER = "<!-- Strike Her Heart workflow snapshot; generated by task.py -->"
TEMPLATE = Path(__file__).resolve().parents[1] / "assets/workflow.html"


def embedded_json(value):
    """Keep all user data inside the JS value, including closing script tags."""
    encoded = json.dumps(value, ensure_ascii=False, allow_nan=False)
    for character, replacement in (("<", "\\u003c"), (">", "\\u003e"),
                                   ("&", "\\u0026"), ("\u2028", "\\u2028"),
                                   ("\u2029", "\\u2029")):
        encoded = encoded.replace(character, replacement)
    return encoded


def render_workflow(root, checked_summary, name="", updated_at=""):
    """Write only workflow.html; never change manifest, history or evidence.

    The caller must use task.summary(data, root) before rendering. This function
    preserves its execution, completion, workQueue and canonical stateContracts
    verbatim. Queue leases and retry times remain observations from that snapshot;
    rendering never claims, resumes, retries or reaps work.
    It does not infer lifecycle success from page totals, promote statuses or
    independently authenticate supplied observations. Legacy/missing lifecycle
    fields remain missing so the renderer can explicitly request re-verification.
    """
    root = Path(root).resolve()
    destination = root / "workflow.html"
    if destination.is_symlink():
        raise ValueError("Workflow output must not be a symlink.")
    if destination.exists():
        if not destination.is_file():
            raise ValueError("Workflow output must be a regular file.")
        with destination.open("r", encoding="utf-8") as previous:
            if previous.readline().rstrip("\n") != MARKER:
                raise ValueError("Existing workflow.html is not a generated snapshot; refusing to overwrite it.")
    template = TEMPLATE.read_text(encoding="utf-8")
    if template.count(PLACEHOLDER) != 1:
        raise ValueError("Workflow template must contain exactly one data placeholder.")
    generated_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    payload = dict(checked_summary)
    payload["view"] = {
        "name": name, "generatedAt": generated_at,
        "recordedUpdatedAt": updated_at, "mode": "snapshot"
    }
    document = MARKER + "\n" + template.replace(PLACEHOLDER, embedded_json(payload))
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=root, prefix=".workflow-",
                suffix=".tmp", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(document)
            handle.flush()
            os.fsync(handle.fileno())
        # Recheck before replacement; os.replace never follows the final link.
        if destination.is_symlink():
            raise ValueError("Workflow output must not be a symlink.")
        os.replace(str(temporary), str(destination))
    finally:
        if temporary and temporary.exists():
            temporary.unlink()
    return {
        "path": str(destination), "taskId": checked_summary["taskId"],
        "revision": checked_summary["revision"], "generatedAt": generated_at,
        "snapshot": True, "recordingOnly": True,
        "taskRecordChanged": False,
        "meaning": "Read-only snapshot of recorded progress; not a new interaction check."
    }
